import { fileURLToPath } from 'node:url'
import { defineConfig, lazyPlugins } from 'vite-plus'
import react, { reactCompilerPreset } from '@vitejs/plugin-react'
import babel from '@rolldown/plugin-babel'
import tailwindcss from '@tailwindcss/vite'
import { tanstackRouter } from '@tanstack/router-plugin/vite'

// The layers under src/, lowest first, and what each may not import. `frontend/AGENTS.md`
// ("Where code goes") says what belongs in each.
//
// `no-restricted-imports` compares the import as written, not the file it resolves to. That
// is why crossing a folder is always spelled `@/…`, and why climbing out with `../` is banned
// alongside: otherwise a relative path would walk straight past the rule.
const LAYERS = ['lib', 'domain', 'testing', 'data', 'checks', 'components', 'hooks', 'features']
const FEATURES = ['working-session', 'reguleringer', 'kjoring', 'parametre']
const ABOVE_ALL = ['@/app/**', '@/routes/**']
const above = (layer: string) => LAYERS.slice(LAYERS.indexOf(layer) + 1).map((l) => `@/${l}/**`)

type RestrictedImports = ['error', { patterns: { group: string[]; message: string }[] }]
const restrict = (files: string[], banned: string[], message: string) => {
  const rule: RestrictedImports = ['error', { patterns: [{ group: banned, message }] }]
  return { files, rules: { 'no-restricted-imports': rule } }
}
const DOWNWARDS = 'Imports point downwards only, see "Where code goes" in frontend/AGENTS.md.'

const layerRules = [
  restrict(['src/lib/**'], [...ABOVE_ALL, ...above('lib'), '../**'], DOWNWARDS),
  restrict(
    ['src/domain/**'],
    // Besides the layers above it: nothing that renders, fetches or draws. The rules here
    // have to run in a plain Node test and load on a page with no map.
    [
      ...ABOVE_ALL,
      ...above('testing'),
      '../**',
      'react',
      'react-dom',
      'ol',
      'ol/**',
      '@tanstack/**',
      'zustand',
    ],
    'domain/ is pure: no React, OpenLayers, fetching or state. ' + DOWNWARDS,
  ),
  restrict(['src/testing/**'], [...ABOVE_ALL, ...above('testing'), '../**'], DOWNWARDS),
  restrict(['src/data/**'], [...ABOVE_ALL, ...above('data'), '../**'], DOWNWARDS),
  restrict(['src/checks/**'], [...ABOVE_ALL, ...above('checks'), '../**'], DOWNWARDS),
  // components/ and hooks/ are one layer: useConfirm renders a ui/ dialog.
  restrict(
    ['src/components/**', 'src/hooks/**'],
    [...ABOVE_ALL, '@/checks/**', '@/features/**', '../../**'],
    DOWNWARDS,
  ),
  ...FEATURES.flatMap((feature) => {
    const others = FEATURES.filter((f) => f !== feature).map((f) => `@/features/${f}/**`)
    const message =
      'A feature does not import another feature. Move what both need down a layer. ' + DOWNWARDS
    return [
      // Two rules per feature because `../` means different things at the two depths: from
      // the feature's own folder it leaves the feature, from a subfolder it stays inside.
      restrict([`src/features/${feature}/*`], [...ABOVE_ALL, ...others, '../**'], message),
      restrict([`src/features/${feature}/*/**`], [...ABOVE_ALL, ...others, '../../**'], message),
    ]
  }),
  restrict(['src/routes/**'], ['@/app/**', '../**'], DOWNWARDS),
]

// https://vite.dev/config/
export default defineConfig({
  // Match the repo's existing style (semicolon-free, single-quote) so adopting
  // oxfmt doesn't churn every file. oxfmt is Prettier-compatible.
  fmt: {
    semi: false,
    singleQuote: true,
  },
  lint: {
    // Generated by the TanStack Router plugin from src/routes/.
    ignorePatterns: ['src/routeTree.gen.ts'],
    plugins: ['react', 'typescript', 'oxc', 'import', 'jsx-a11y'],
    rules: {
      'react/rules-of-hooks': 'error',
      'import/no-cycle': 'error',
      // A label here wraps its control, and the control is one of ours. Without the names
      // the rule cannot see that `<Input>` renders an input.
      'jsx-a11y/label-has-associated-control': [
        'error',
        { controlComponents: ['Input', 'Checkbox'] },
      ],
      'react/only-export-components': [
        'warn',
        {
          allowConstantExport: true,
        },
      ],
      'vite-plus/prefer-vite-plus-imports': 'error',
    },
    overrides: [
      {
        // A route file exports `Route` next to its component; the router plugin handles
        // hot reload for those.
        files: ['src/routes/**'],
        rules: { 'react/only-export-components': 'off' },
      },
      {
        // Vendored shadcn: a component and its `cva` variants are exported together.
        files: ['src/components/ui/**'],
        rules: { 'react/only-export-components': 'off' },
      },
      ...layerRules,
    ],
    options: {
      typeAware: true,
      typeCheck: true,
      // A warning nobody has to act on is a warning nobody reads.
      denyWarnings: true,
    },
    jsPlugins: [
      {
        name: 'vite-plus',
        specifier: 'vite-plus/oxlint-plugin',
      },
    ],
  },
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  // React Compiler (auto-memoization) via the Rolldown babel preset. React 19 uses the
  // built-in react/compiler-runtime, so no react-compiler-runtime package is needed.
  plugins: lazyPlugins(() => [
    // File-based routes: generates src/routeTree.gen.ts from src/routes/, and splits each
    // route's component into its own chunk. Must come before the React plugin.
    tanstackRouter({ target: 'react', autoCodeSplitting: true }),
    react(),
    babel({ presets: [reactCompilerPreset()] }),
    tailwindcss(),
  ]),
})
